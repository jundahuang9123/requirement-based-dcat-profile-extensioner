#!/usr/bin/env python3
"""List every open marker of the RQ2 paper and write the list into paper/README.md.

Markers (defined in paper/main.tex and paper/results/main-numbers.tex):
  \\todo{...}    a decision or a piece of work that is still open
  \\verify{...}  a claim or a bibliography detail that has not been checked against a primary source
  \\res{s}{c}{m} a main-result slot; it prints a red "?" until the RQ2 evaluator writes its value
  \\tbd          a result cell typed directly (prints the same red "?")
Bibliography entries whose note starts with "verify" are listed as well.

The list replaces the text between the lines "<!-- markers:begin -->" and "<!-- markers:end -->" in paper/README.md.
The local, gitignored directory paper/sections/local/ is not scanned.

Usage: python paper/scripts/list_markers.py          (rewrite the README block)
       python paper/scripts/list_markers.py --print  (print the block only)
"""
from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
README = PAPER / "README.md"
BEGIN, END = "<!-- markers:begin -->", "<!-- markers:end -->"


def sources() -> list[Path]:
    files = [PAPER / "main.tex"]
    for folder in ("sections", "figures", "tables"):
        files += sorted((PAPER / folder).glob("*.tex"))
    return [f for f in files if f.exists()]


def balanced(text: str, start: int) -> tuple[str, int]:
    """Return the content of the brace group opening at text[start] == '{' and the index after it."""
    depth, i = 0, start
    while i < len(text):
        if text[i] == "\\":
            i += 2
            continue
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1:i], i + 1
        i += 1
    return text[start + 1:], len(text)


def strip_comments(text: str) -> str:
    """Blank out LaTeX comments (keeps offsets, so line numbers stay right)."""
    return re.sub(r"(?<!\\)%[^\n]*", lambda m: " " * len(m.group(0)), text)


def one_line(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def scan() -> tuple[dict[str, list[tuple[str, int, str]]], Counter, list[tuple[str, int]]]:
    found: dict[str, list[tuple[str, int, str]]] = {"todo": [], "verify": []}
    res: Counter = Counter()
    tbd: list[tuple[str, int]] = []
    for path in sources():
        raw = path.read_text(encoding="utf-8")
        text = strip_comments(raw)
        rel = path.relative_to(PAPER).as_posix()
        if rel == "main.tex":
            # skip the definitions of the markers themselves
            text = re.sub(r"\\newcommand\{\\(todo|verify|tbd)\}[^\n]*", lambda m: " " * len(m.group(0)), text)
        for m in re.finditer(r"\\(todo|verify)\s*\{", text):
            body, _ = balanced(text, m.end() - 1)
            line = text.count("\n", 0, m.start()) + 1
            found[m.group(1)].append((rel, line, one_line(body)))
        for m in re.finditer(r"\\res\s*\{([^}]*)\}\s*\{([^}]*)\}\s*\{([^}]*)\}", text):
            res[(m.group(1), m.group(2), m.group(3))] += 1
        for m in re.finditer(r"\\tbd\b", text):
            tbd.append((rel, text.count("\n", 0, m.start()) + 1))
    return found, res, tbd


def bib_verify() -> list[tuple[str, str]]:
    out = []
    text = (PAPER / "references.bib").read_text(encoding="utf-8")
    for m in re.finditer(r"@\w+\s*\{\s*([^,\s]+)\s*,(.*?)\n\}", text, re.S):
        note = re.search(r"\bnote\s*=\s*\{(.*?)\}\s*,?\s*$", m.group(2), re.S | re.M)
        if note and "verify" in note.group(1).lower():
            out.append((m.group(1), one_line(note.group(1))))
    return out


def block() -> str:
    found, res, tbd = scan()
    lines = [BEGIN, "", "_Generated by `python paper/scripts/list_markers.py`; do not edit this block by hand._", ""]
    lines.append(f"**Counts.** {len(found['verify'])} `\\verify`, {len(found['todo'])} `\\todo`, "
                 f"{sum(res.values())} `\\res` uses ({len(res)} distinct result slots), {len(tbd)} direct `\\tbd` cells, "
                 f"{len(bib_verify())} bibliography entries with a printed verify note.")
    for kind, title in (("verify", "Verify items (`\\verify{...}`)"), ("todo", "TODO items (`\\todo{...}`)")):
        lines += ["", f"#### {title}", ""]
        for rel, line, body in found[kind]:
            lines.append(f"- `{rel}:{line}`: {body}")
    lines += ["", "#### Bibliography entries with a verify note (`references.bib`)", ""]
    for key, note in bib_verify():
        lines.append(f"- `{key}`: {note}")
    lines += ["", "#### Main-result slots (`\\res{scope}{condition}{measure}`, all print `?` now)", ""]
    by_scope: dict[str, list[str]] = {}
    for (scope, cond, measure), n in sorted(res.items()):
        by_scope.setdefault(scope, []).append(f"{cond}/{measure}" + (f" ×{n}" if n > 1 else ""))
    for scope, slots in by_scope.items():
        lines.append(f"- `{scope}`: " + ", ".join(slots))
    if tbd:
        lines += ["", "#### Direct `\\tbd` cells", ""]
        per_file = Counter(rel for rel, _ in tbd)
        lines.append("- " + ", ".join(f"`{rel}` ({n})" for rel, n in sorted(per_file.items())))
    lines += ["", END]
    return "\n".join(lines)


def main() -> int:
    text = block()
    if "--print" in sys.argv:
        print(text)
        return 0
    readme = README.read_text(encoding="utf-8")
    if BEGIN not in readme or END not in readme:
        raise SystemExit(f"{README} lacks the {BEGIN} / {END} lines")
    head, rest = readme.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    README.write_text(head + text + tail, encoding="utf-8")
    print(f"wrote the marker list into {README.relative_to(PAPER.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
