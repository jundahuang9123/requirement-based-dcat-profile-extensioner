#!/usr/bin/env python3
"""Generate the development-run macros and table of the RQ2 paper from the numbers-only input files
paper/inputs/pilot-runs-2026-11-13.md (runs 1, 2 and the rules baseline) and
paper/inputs/dev-runs-2026-11-14-run3.md (run 3). All of these runs are contaminated (see those files):
a debugging history, not results.

Every development-run number in the paper comes from these files through this script; nothing is typed by hand.
Outputs (overwritten):
  paper/results/pilot-numbers.tex  macros: \\pilot{<case>}{<run>}{<field>}, \\pilotkind{<case>}{<run>}{<kind>}
  paper/tables/pilot-runs.tex      the main pilot table (booktabs, LNCS width)

Cases: jrc, stat. Runs: rules, run1, run2. Usage: python paper/scripts/make_pilot_tables.py
"""
from __future__ import annotations

import re
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
SOURCES = [PAPER / "inputs" / "pilot-runs-2026-11-13.md", PAPER / "inputs" / "dev-runs-2026-11-14-run3.md"]
MACROS = PAPER / "results" / "pilot-numbers.tex"
TABLE = PAPER / "tables" / "pilot-runs.tex"

CASES = {"JRC": "jrc", "Stat": "stat"}
RUNS = {"rules (mock)": "rules", "gpt-oss-120b run 1": "run1", "gpt-oss-120b run 2": "run2", "gpt-oss-120b run 3": "run3"}
KINDS = {"reuse": "reuse", "refine": "refine", "mint property": "mintproperty", "mint class": "mintclass"}


def thousands(text: str) -> str:
    """'133,326' -> '133{,}326' for math-safe LaTeX; plain digits stay."""
    return text.replace(",", "{,}")


def parse() -> tuple[dict, dict]:
    lines = [line for source in SOURCES for line in source.read_text(encoding="utf-8").splitlines()]
    rows: dict[tuple[str, str], dict[str, str]] = {}
    header: list[str] | None = None
    for line in lines:
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if cells[0] == "case":
            header = cells
            continue
        if header is None or set(cells[0]) <= {"-"}:
            continue
        record = dict(zip(header, cells))
        case, run = CASES[record["case"]], RUNS[record["provider"]]
        calls, cached = re.fullmatch(r"(\d+) \((\d+)\)", record["calls (cached)"]).groups()
        tok_in, tok_out = [t.strip() for t in record["in / out tokens"].split("/")]
        conf = record["conformance"]
        verdict = conf.split(" (")[0]
        counts = {word: number for number, word in re.findall(r"(\d+) (added|tightened|loosened|warnings?)", conf)}
        rows[(case, run)] = {
            "wall": record["wall s"], "calls": calls, "cached": cached,
            "intok": tok_in, "outtok": tok_out,
            "addressed": record["addressed"], "partial": record["partial"],
            "pending": record["pending review"], "unaddressed": record["unaddressed"],
            "covered": record.get("covered by base", "0"),
            "included": record["included"], "rejected": record["rejected"],
            "needsreview": record["needs review"], "extrate": record["ext. rate"],
            "verdict": verdict, "added": counts.get("added", ""), "tightened": counts.get("tightened", ""),
            "loosened": counts.get("loosened", "0"),
            "warnings": counts.get("warnings", counts.get("warning", "0")),
        }
    kinds: dict[tuple[str, str], dict[str, str]] = {}
    for line in lines:
        m = re.match(r"- (JRC|Stat) run (\d): (.+)\.$", line.strip())
        if not m:
            continue
        case, run = CASES[m.group(1)], f"run{m.group(2)}"
        found = {KINDS[k]: n for k, n in ((p.rsplit(" ", 1)[0], p.rsplit(" ", 1)[1]) for p in m.group(3).split(", "))}
        kinds[(case, run)] = {k: found.get(k, "0") for k in KINDS.values()}
    return rows, kinds


def write_macros(rows: dict, kinds: dict) -> None:
    out = [
        "% Generated by paper/scripts/make_pilot_tables.py from paper/inputs/pilot-runs-2026-11-13.md.",
        "% Do not edit by hand. \\pilot{case}{run}{field}: case jrc|stat, run rules|run1|run2.",
        "\\makeatletter",
        "\\newcommand{\\pilot}[3]{\\@ifundefined{pilot@#1@#2@#3}{\\textbf{??}}{\\@nameuse{pilot@#1@#2@#3}}}",
        "\\newcommand{\\pilotkind}[3]{\\@ifundefined{pilotkind@#1@#2@#3}{\\textbf{??}}{\\@nameuse{pilotkind@#1@#2@#3}}}",
    ]
    for (case, run), record in sorted(rows.items()):
        for field, value in record.items():
            value = thousands(value) if field in ("intok", "outtok") else value
            out.append(f"\\@namedef{{pilot@{case}@{run}@{field}}}{{{value}}}")
    for (case, run), record in sorted(kinds.items()):
        for kind, value in record.items():
            out.append(f"\\@namedef{{pilotkind@{case}@{run}@{kind}}}{{{value}}}")
    out.append("\\makeatother")
    MACROS.parent.mkdir(parents=True, exist_ok=True)
    MACROS.write_text("\n".join(out) + "\n", encoding="utf-8")


def write_table(rows: dict, kinds: dict) -> None:

    # Transposed layout: runs are columns (grouped by case), measures are rows with whole-word labels.
    runs = [(case, run) for case in ("jrc", "stat") for run in ("rules", "run1", "run2", "run3")]
    head = {"rules": "rules", "run1": "run\\,1", "run2": "run\\,2", "run3": "run\\,3"}

    def cells(get) -> str:
        return " & ".join(get(case, run) for case, run in runs)

    def kind(field):
        def get(case, run):
            k = kinds.get((case, run))
            return k[field] if k else "--"
        return get

    def plain(field):
        return lambda case, run: rows[(case, run)][field]

    def calls(case, run):
        r = rows[(case, run)]
        return f"{r['calls']} ({r['cached']})"

    def conf(case, run):
        r = rows[(case, run)]
        return f"{r['added']}/{r['tightened']}/{r['warnings']}"

    body = [
        ("\\emph{Atoms}", None),
        ("addressed", plain("addressed")),
        ("addressed in part", plain("partial")),
        ("covered by the base", plain("covered")),
        ("pending review", plain("pending")),
        ("unaddressed", plain("unaddressed")),
        ("\\emph{Changes}", None),
        ("included", plain("included")),
        ("\\quad reuse", kind("reuse")),
        ("\\quad refine", kind("refine")),
        ("\\quad mint property", kind("mintproperty")),
        ("\\quad mint class", kind("mintclass")),
        ("withdrawn by the repairer", plain("rejected")),
        ("in the review queue", plain("needsreview")),
        ("extension rate", plain("extrate")),
        ("\\emph{Conformance}", None),
        ("added/tightened/warnings", conf),
        ("\\emph{Cost}", None),
        ("model calls (cached)", calls),
        ("wall time (s)", plain("wall")),
    ]
    out = [
        "% Generated by paper/scripts/make_pilot_tables.py from paper/inputs/pilot-runs-2026-11-13.md and",
        "% paper/inputs/dev-runs-2026-11-14-run3.md. Do not edit by hand. Rules runs: the file gives no breakdown by kind",
        "% beyond 'reuse or refine only' (shown as --).",
        "\\begin{tabular}{@{}l rrrr rrrr@{}}",
        "\\toprule",
        " & \\multicolumn{4}{c}{DCAT-AP-JRC (17 atoms)} & \\multicolumn{4}{c}{StatDCAT-AP (14 atoms)} \\\\",
        "\\cmidrule(lr){2-5}\\cmidrule(l){6-9}",
        " & " + " & ".join(head[run] for _, run in runs) + " \\\\",
        "\\midrule",
    ]
    for label_text, getter in body:
        if getter is None:
            out.append(f"{label_text} \\\\")
        else:
            out.append(f"{label_text} & {cells(getter)} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    TABLE.parent.mkdir(parents=True, exist_ok=True)
    TABLE.write_text("\n".join(out) + "\n", encoding="utf-8")


def main() -> int:
    rows, kinds = parse()
    assert len(rows) == 8, rows.keys()
    assert len(kinds) == 6, kinds.keys()
    write_macros(rows, kinds)
    write_table(rows, kinds)
    print(f"{len(rows)} runs, {len(kinds)} kind breakdowns -> {MACROS.relative_to(PAPER.parent)}, {TABLE.relative_to(PAPER.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
